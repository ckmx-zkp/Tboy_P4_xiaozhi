#ifndef _BOARD_CONFIG_H_
#define _BOARD_CONFIG_H_

#include <driver/gpio.h>

// ESP32-S3-V1.0.1 空调面板。模组 ESP32-S3-WROOM-1-N16R8。
// 原理图 D:/User/SCH_ESP32-S3-V1_0_1_2026-09-22.pdf
// 音频网与 USB 摄像头大板相同：ES8311 0x18、ES7210 0x41、NS4150B、J7。
// PA_EN 不接 GPIO46。PCA9557（0x19）IO1 驱动 NS4150B CTRL，R40 10k 下拉。
// GPIO12/13/14 同时标成并口屏数据线，本板不初始化屏幕，留给 I2S。

#define AUDIO_INPUT_SAMPLE_RATE  24000
#define AUDIO_OUTPUT_SAMPLE_RATE 24000
#define AUDIO_INPUT_REFERENCE    true

#define AUDIO_I2S_GPIO_MCLK GPIO_NUM_38
#define AUDIO_I2S_GPIO_WS   GPIO_NUM_13
#define AUDIO_I2S_GPIO_BCLK GPIO_NUM_14
#define AUDIO_I2S_GPIO_DIN  GPIO_NUM_12
#define AUDIO_I2S_GPIO_DOUT GPIO_NUM_45

#define AUDIO_CODEC_I2C_SDA_PIN  GPIO_NUM_1
#define AUDIO_CODEC_I2C_SCL_PIN  GPIO_NUM_2
#define AUDIO_CODEC_ES8311_ADDR  ES8311_CODEC_DEFAULT_ADDR
#define AUDIO_CODEC_ES7210_ADDR  0x82
#define AUDIO_CODEC_PCA9557_ADDR 0x19
#define AUDIO_CODEC_PA_IO        1

#define BOOT_BUTTON_GPIO         GPIO_NUM_0

#endif
